/**
 * Filter and query verified leads by keyword, district, and platform
 */
export function queryVerifiedSocialMediaLeads(
  keyword: string = '',
  district: string = 'Semua Wilayah',
  platform: LeadPlatform | 'all' = 'all'
): BusinessLead[] {
  return VERIFIED_AMBON_SOCIAL_LEADS.filter(lead => {
    // Platform match
    if (platform !== 'all' && lead.platformSumber !== platform) {
      return false;
    }

    // District match
    if (district && district !== 'Semua Wilayah') {
      const distLower = district.toLowerCase();
      if (!lead.wilayahKecamatan.toLowerCase().includes(distLower)) {
        return false;
      }
    }

    // Keyword match
    if (keyword && keyword !== 'Semua' && keyword.trim() && keyword !== 'Full Scan Kota Ambon') {
      const q = keyword.toLowerCase();
      const matchName = lead.namaUsaha.toLowerCase().includes(q);
      const matchCat = lead.kategoriBisnis.toLowerCase().includes(q);
      const matchHandle = lead.socialHandle?.toLowerCase().includes(q);
      const matchProduct = lead.rekomendasiProduk.toLowerCase().includes(q);
      const matchAlamat = lead.alamatLengkap?.toLowerCase().includes(q);
      if (!matchName && !matchCat && !matchHandle && !matchProduct && !matchAlamat) {
        return false;
      }
    }

    return true;
  });
}
