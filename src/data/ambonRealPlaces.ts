/**
 * Filter verified directory leads by keyword, district, or channel
 */
export function queryVerifiedAmbonDirectory(
  keyword?: string,
  district?: string,
  limit: number = 55
): BusinessLead[] {
  let results = [...VERIFIED_AMBON_BUSINESSES];

  if (district && district !== 'Semua Wilayah') {
    results = results.filter(b => b.wilayahKecamatan.toLowerCase() === district.toLowerCase());
  }

  if (keyword && keyword.trim() !== '' && keyword !== 'Semua' && keyword !== 'Full Scan Kota Ambon') {
    const kw = keyword.toLowerCase().trim();
    results = results.filter(b => 
      b.namaUsaha.toLowerCase().includes(kw) ||
      b.kategoriBisnis.toLowerCase().includes(kw) ||
      b.wilayahKecamatan.toLowerCase().includes(kw) ||
      (b.alamatLengkap && b.alamatLengkap.toLowerCase().includes(kw))
    );
  }

  if (results.length === 0) {
    results = [...VERIFIED_AMBON_BUSINESSES];
  }

  return results.slice(0, limit);
}
